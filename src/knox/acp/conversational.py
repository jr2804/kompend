"""Conversational agent with native PydanticAI tool-calling loop.

Driven by an :class:`~knox.acp.definitions.AgentDefinition`, this agent
uses a PydanticAI :class:`~pydantic_ai.Agent` with a native
:class:`~pydantic_ai.toolsets.FunctionToolset` so the framework handles
schema generation, tool-call parsing, retry budgeting, and message history.

The system prompt comes from the agent definition's ``[prompt].system``.
Tool schemas are generated by PydanticAI from the toolset functions'
type hints and docstrings — no manual manifest needed.
"""

from __future__ import annotations

import time
from typing import Any

from acp import PromptResponse
from acp.schema import AgentMessageChunk, TextContentBlock
from pydantic_ai import Agent
from pydantic_ai.capabilities import Hooks

from knox.acp._constants import (
    CONTENT_TYPE_TEXT,
    MSG_ID_PREFIX,
    SESSION_UPDATE_MESSAGE_CHUNK,
    STOP_REASON_END_TURN,
    STOP_REASON_MAX_TOKENS,
)
from knox.acp.definitions import AgentDefinition
from knox.acp.tools import build_toolset
from knox.agents.knox_model import KnoxModel
from knox.llm.models import build_model
from knox.llm.usage import UsageTracker
from knox.logging import get_logger

logger = get_logger(__name__)


class ConversationalAgent:
    """Tool-calling conversational loop driven by a native PydanticAI Agent."""

    def __init__(
        self,
        definition: AgentDefinition,
        model: str,
        base_dir: str,
    ) -> None:
        self._definition = definition
        self._model = model
        self._base_dir = base_dir
        self._usage_tracker = UsageTracker()
        # Notification state (set per run() call)
        self._notify_conn: Any = None
        self._notify_session_id: str = ""
        self._notify_message_id: str = ""

    async def run(
        self,
        user_message: str,
        session_id: str,
        conn: Any | None = None,
    ) -> PromptResponse:
        """Run the conversational loop for a single user prompt.

        PydanticAI handles the tool-calling loop natively — the agent
        calls tools, receives results, and iterates until it produces
        a final text answer.

        Args:
            user_message: The user's text prompt.
            session_id: ACP session ID (for progress notifications).
            conn: ACP connection for sending progress chunks (*None* = silent).

        Returns:
            :class:`PromptResponse` with the final answer.
        """
        self._notify_conn = conn
        self._notify_session_id = session_id
        self._notify_message_id = f"{MSG_ID_PREFIX}{int(time.time() * 1000)}"

        definition = self._definition

        try:
            agent = self._build_agent()
            result = await agent.run(
                user_message,
                instructions=definition.prompt.system,
            )
            content = result.output or "(no response)"
            await self._notify(conn, session_id, self._notify_message_id, content)
            return PromptResponse(stopReason=STOP_REASON_END_TURN)
        except Exception as exc:
            logger.warning(
                "Conversational agent '%s' failed: %s",
                definition.name,
                exc,
            )
            error_msg = f"I encountered an error: {exc}"
            await self._notify(conn, session_id, self._notify_message_id, error_msg)
            return PromptResponse(stopReason=STOP_REASON_MAX_TOKENS)

    def _build_agent(self) -> Agent[None, str]:
        """Build a PydanticAI Agent with native toolset."""
        definition = self._definition

        # Build the native toolset from the agent definition's enabled tools.
        toolset = build_toolset(
            base_dir=self._base_dir,
            enabled=definition.tools.enabled,
        )

        # Wire up ACP progress notifications via a Hooks capability.
        hooks = Hooks()
        notify_conn = self._notify_conn
        notify_session_id = self._notify_session_id
        notify_message_id = self._notify_message_id

        @hooks.on.before_tool_execute
        async def _notify_before_tool(
            ctx: Any,
            call: Any,
            tool_def: Any,
            args: Any,
        ) -> Any:
            """Send ACP progress notification before tool execution."""
            if notify_conn is None:
                return args
            try:
                chunk = AgentMessageChunk(
                    content=TextContentBlock(
                        type=CONTENT_TYPE_TEXT,
                        text=f"Calling {tool_def.name}...",
                    ),
                    messageId=notify_message_id,
                    sessionUpdate=SESSION_UPDATE_MESSAGE_CHUNK,
                )
                await notify_conn.session_update(
                    session_id=notify_session_id,
                    update=chunk,
                )
            except Exception:
                logger.debug("Failed to send progress notification", exc_info=True)
            return args

        model = KnoxModel(
            build_model(self._model),
            usage_tracker=self._usage_tracker,
        )
        return Agent(
            model,
            toolsets=[toolset],
            capabilities=[hooks],
            retries=definition.behavior.max_turns,
        )

    async def _notify(  # noqa: PLR6301
        self,
        conn: Any | None,
        session_id: str,
        message_id: str,
        text: str,
    ) -> None:
        """Send a progress chunk as an AgentMessageChunk notification."""
        if conn is None:
            return
        try:
            chunk = AgentMessageChunk(
                content=TextContentBlock(type=CONTENT_TYPE_TEXT, text=text),
                messageId=message_id,
                sessionUpdate=SESSION_UPDATE_MESSAGE_CHUNK,
            )
            await conn.session_update(session_id=session_id, update=chunk)
        except Exception:
            logger.debug("Failed to send progress notification", exc_info=True)
