"""``knox memory`` — manage query memory and context synthesis."""

from __future__ import annotations

from pathlib import Path

import typer

from knox.cli.app import app
from knox.cli.args_memory import MemoryAnswer, MemoryFeedback, MemoryLimit, MemoryQuery, MemoryTopK
from knox.core.config import resolve_config
from knox.memory.store import MemoryStore

memory_app = typer.Typer(
    name="memory",
    help="Manage query memory and context synthesis.",
    no_args_is_help=True,
)
app.add_typer(memory_app)


def _get_memory_store(ctx: typer.Context | None) -> tuple[MemoryStore, Path]:
    """Resolve the memory store and project base directory from context."""
    wiki_dir_override = ctx.obj.get("wiki_dir") if ctx and ctx.obj else None
    cfg = resolve_config(cli_overrides={"paths.wiki_dir": wiki_dir_override} if wiki_dir_override else {})
    paths = cfg.get("paths")
    output_dir_path = Path(paths["output_dir"])
    base_dir = output_dir_path.parent
    embed_model = cfg.get("compile.embedding.model")
    return MemoryStore(base_dir=base_dir, embedding_model=embed_model), base_dir


@memory_app.command("add", help="Add a query/answer pair to the memory log.")
def memory_add(
    ctx: typer.Context,
    query: MemoryQuery,
    answer: MemoryAnswer,
    feedback: MemoryFeedback = None,
) -> None:
    """Add a query, answer, and optional feedback to the memory store."""
    store, _base_dir = _get_memory_store(ctx)
    try:
        store.add_entry(query=query, answer=answer, feedback=feedback)
        typer.echo("✓ Memory entry added successfully.")
    except Exception as exc:
        typer.echo(f"Error adding memory entry: {exc}", err=True)
        raise typer.Exit(1)
    finally:
        store.close()


@memory_app.command("search", help="Search past memory entries semantically.")
def memory_search(
    ctx: typer.Context,
    query: MemoryQuery,
    top_k: MemoryTopK = 5,
) -> None:
    """Search the memory store for past queries and answers."""
    store, _base_dir = _get_memory_store(ctx)
    try:
        results = store.search(query=query, top_k=top_k)
        if not results:
            typer.echo("No relevant memory entries found.")
            return

        typer.echo(f"Found {len(results)} relevant memory entries:\n")
        for i, res in enumerate(results, 1):
            typer.echo(f"[{i}] Query: {res['query']}")
            typer.echo(f"    Answer: {res['answer']}")
            if res.get("feedback"):
                typer.echo(f"    Feedback: {res['feedback']}")
            typer.echo(f"    Score: {res['score']:.4f}\n")
    except Exception as exc:
        typer.echo(f"Error searching memory: {exc}", err=True)
        raise typer.Exit(1)
    finally:
        store.close()


@memory_app.command("synthesize", help="Synthesize recent memory into a system context file.")
def memory_synthesize(
    ctx: typer.Context,
    limit: MemoryLimit = 20,
) -> None:
    """Review recent memory entries and generate a system context file."""
    store, base_dir = _get_memory_store(ctx)

    try:
        entries = store.get_recent_entries(limit=limit)
        if not entries:
            typer.echo("No memory entries found to synthesize.")
            return

        # For now, we'll create a simple markdown summary.
        # In a full implementation, this would call an LLM to distill the entries.
        context_path = base_dir / "sources" / "_memory" / "system_context.md"
        context_path.parent.mkdir(parents=True, exist_ok=True)

        with open(context_path, "w", encoding="utf-8") as f:
            f.write("# System Context (Auto-Generated)\n\n")
            f.write("This file is automatically generated based on recent user queries and feedback.\n\n")
            f.write("## Recent Query Themes\n\n")

            # Simple thematic grouping (placeholder for LLM synthesis)
            queries = [e["query"] for e in entries]
            for q in queries[:10]:  # Just list the last 10 for now
                f.write(f"- {q}\n")

        typer.echo(f"✓ Synthesized context written to {context_path}")

    except Exception as exc:
        typer.echo(f"Error synthesizing memory: {exc}", err=True)
        raise typer.Exit(1)
    finally:
        store.close()
