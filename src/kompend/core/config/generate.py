"""Code-driven TOML generation for kompend configuration.

Generates scaffold config from :data:`DEFAULTS` without a Jinja2 template,
and provides utilities for extracting keys from TOML text (used by the
sync test against ``kompend.toml.example``).
"""

from __future__ import annotations

import re
import tomllib
from enum import StrEnum
from typing import Any, cast

import tomli_w
from pydantic import BaseModel

from kompend.core.config._configs import KompendConfig
from kompend.core.config._core import DEFAULTS, flat_keys
from kompend.types import ConfigValue

_HIDDEN_KEYS: frozenset[str] = frozenset(
    {
        "compile.sources_dir",
        "compile.output_dir",
    }
)

_SECTION_ORDER: tuple[str, ...] = (
    "paths",
    "notes",
    "compile",
    "dedup",
    "organize",
    "lint",
    "eval",
    "trust",
    "ignore",
    "search",
    "hooks",
)

_SCAFFOLD_HEADER = "# kompend configuration — generated by `kompend init`.\n# Edit values as needed. See kompend.toml.example for full reference.\n\n"

_SECTION_RE = re.compile(r"^\s*\[+([^\]]+)\]+")
_KEY_RE = re.compile(r"^#?\s*([\w.\-]+)\s*=")

#: Supplement to the schema-derived choices: keys whose schema type is
#: plain ``str`` (or ``str | None``) but whose documented value domain is
#: closed. Order is the presentation order used in trailing comments.
_STR_ENUM_CHOICES: dict[str, tuple[str, ...]] = {
    "compile.compiler": ("graph", "wicer"),
    "compile.start_at_tier": ("index", "chunk", "resolve", "compile", "output"),
    "compile.stop_at_tier": ("index", "chunk", "resolve", "compile", "output"),
    "compile.llm.reasoning_effort": ("none", "minimal", "low", "medium", "high", "xhigh", "default"),
    # Accepts the boolean ``false`` to disable; listed as its literal form.
    "compile.llm.context_manager": ("default", "aggressive", "sliding", "false"),
    "compile.output.flavor": ("obsidian", "gfm", "mkdocs", "mdx", "quarto", "myst", "standard"),
    "dedup.matchers": ("embedding", "minhash"),
}


def generate_scaffold_config() -> str:
    """Generate TOML config text from :data:`DEFAULTS`.

    ``None`` values, empty dicts, and hidden keys are omitted. Sections
    are reordered for readability. Enum-like keys carry a trailing
    comment listing the remaining valid values. The result is valid
    TOML suitable for writing to ``.kompend/config.toml`` during
    ``kompend init``.
    """
    cleaned = cast("dict[str, Any]", _clean_defaults(DEFAULTS))
    reordered = _reorder_sections(cleaned)
    text = tomli_w.dumps(reordered)
    return _SCAFFOLD_HEADER + _annotate_value_domains(text, enum_choices())


def enum_choices() -> dict[str, tuple[str, ...]]:
    """Map dotted config keys to their closed value domain.

    Derived from StrEnum-typed leaves of the config schema plus
    :data:`_STR_ENUM_CHOICES` for str-typed keys with a documented,
    closed domain. Used to annotate generated config (and the docs)
    with ``key = "value"  # other_value, ...`` trailing comments.
    """
    choices: dict[str, tuple[str, ...]] = {}

    def _walk(model: type[BaseModel], prefix: str = "") -> None:
        for name, field_info in model.model_fields.items():
            dotted = f"{prefix}.{name}" if prefix else name
            annotation = field_info.annotation
            if isinstance(annotation, type) and issubclass(annotation, BaseModel):
                _walk(annotation, dotted)
            elif isinstance(annotation, type) and issubclass(annotation, StrEnum):
                # Dedupe while keeping declaration order (aliases share values).
                choices[dotted] = tuple(dict.fromkeys(member.value for member in annotation))

    _walk(KompendConfig)
    choices.update(_STR_ENUM_CHOICES)
    return choices


def _annotate_value_domains(text: str, choices: dict[str, tuple[str, ...]]) -> str:
    """Append ``# remaining, values`` comments to keys with a closed domain.

    The value currently set on each annotated key is excluded from the
    list, so the comment always shows what the key may be changed to.
    """
    shown = _flatten_values(tomllib.loads(text))
    lines: list[str] = []
    section = ""
    for line in text.splitlines():
        if sect_match := _SECTION_RE.match(line):
            section = sect_match.group(1)
        elif (key_match := _KEY_RE.match(line)) and section:
            dotted = f"{section}.{key_match.group(1)}"
            domain = choices.get(dotted)
            value = shown.get(dotted)
            if domain is not None and value is not None:
                current = value if isinstance(value, list) else [value]
                remaining = [v for v in domain if v not in current]
                if remaining:
                    annotated = f"{line}  # {', '.join(remaining)}"
                    lines.append(annotated)
                    continue
        lines.append(line)
    return "\n".join(lines) + "\n"


def _flatten_values(data: dict[str, Any], prefix: str = "") -> dict[str, Any]:
    """Flatten nested config dicts to ``{dotted_key: value}``."""
    flat: dict[str, Any] = {}
    for key, value in data.items():
        dotted = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            flat.update(_flatten_values(value, dotted))
        else:
            flat[dotted] = value
    return flat


def _clean_defaults(data: ConfigValue, prefix: str = "") -> ConfigValue:
    """Deep-copy *data*, dropping ``None`` values and hidden keys.

    Empty dicts after cleaning are also removed — they would produce
    empty TOML sections with no useful content.
    """
    if not isinstance(data, dict):
        return data
    result: dict[str, Any] = {}
    for key, value in data.items():
        full = f"{prefix}.{key}" if prefix else key
        if full in _HIDDEN_KEYS:
            continue
        cleaned = _clean_defaults(value, full)
        if cleaned is None:
            continue
        if isinstance(cleaned, dict) and not cleaned:
            continue
        result[key] = cleaned
    return result


def _reorder_sections(data: dict[str, Any]) -> dict[str, Any]:
    """Reorder top-level dict keys to match ``_SECTION_ORDER``."""
    ordered: dict[str, Any] = {}
    for section in _SECTION_ORDER:
        if section in data:
            ordered[section] = data[section]
    for key, value in data.items():
        if key not in ordered:
            ordered[key] = value
    return ordered


def get_default_keys() -> set[str]:
    """Return all public leaf dotted keys defined in :data:`DEFAULTS`.

    Hidden keys (deprecated duplicates like ``compile.sources_dir``)
    are excluded. Used by the sync test to verify ``kompend.toml.example``
    documents every key the config system knows about.
    """
    return {k for k in flat_keys(DEFAULTS) if k not in _HIDDEN_KEYS}


def extract_toml_keys(text: str) -> set[str]:
    """Extract dotted config keys from TOML *text*.

    Handles both commented and uncommented lines. Section headers
    (``[compile.llm]``) are combined with bare keys (``default_model =``)
    to produce full dotted paths (``compile.llm.default_model``).
    """
    keys: set[str] = set()
    current_section = ""
    for line in text.splitlines():
        if sect_match := _SECTION_RE.match(line):
            current_section = sect_match.group(1)
            # A section header documents the group path itself (e.g.
            # ``[compile.llm.rlm]`` covers the ``compile.llm.rlm`` key).
            keys.add(current_section)
            continue
        if key_match := _KEY_RE.match(line):
            key = key_match.group(1)
            if current_section:
                keys.add(f"{current_section}.{key}")
            else:
                keys.add(key)
    return keys
